#!/usr/bin/env bash
# Publish one talks-archive shard: check its release assets against the conversion state,
# render it locally, create the GitHub repo with Pages from Actions, push, and upload the originals.
#
#   tools/shards/publish.sh talks-archive-2010-2014 [--root /Users/conet/GitHub/DBetebenner]
#
# Run from the hub repo root. Needs gh (authenticated), quarto and node.
set -euo pipefail

SHARD="${1:?usage: publish.sh <shard> [--root dir]}"
ROOT=/Users/conet/GitHub/DBetebenner
[[ "${2:-}" == "--root" ]] && ROOT="$3"
OWNER=dbetebenner
HUB="$(pwd)"
DIR="$ROOT/$SHARD"
RELEASE="$HUB/work/release/$SHARD"
YEARS="${SHARD#talks-archive-}"
YEARS="${YEARS/-/–}"

[[ -f "$DIR/_quarto.yml" ]] || { echo "no shard at $DIR" >&2; exit 1; }

# Release folder and conversion state must agree exactly; a stray file would be published.
node --input-type=module -e '
import fs from "node:fs"; import yaml from "js-yaml";
const [shard, dir] = process.argv.slice(1);
const st = yaml.load(fs.readFileSync(`catalog/generated/converted/${shard}.yml`, "utf8"), { schema: yaml.CORE_SCHEMA }) || {};
const want = new Set(Object.values(st).flatMap((s) => s.assets || []));
const have = fs.readdirSync(dir);
const extra = have.filter((f) => !want.has(f)), missing = [...want].filter((f) => !have.includes(f));
if (extra.length || missing.length) { console.error("extra:", extra, "missing:", missing); process.exit(1); }
console.log(`${shard}: ${have.length} release assets match the conversion state`);
' "$SHARD" "$RELEASE"

(cd "$DIR" && quarto render >/dev/null 2>"$HUB/work/logs/$SHARD.render.log") || { echo "render failed: work/logs/$SHARD.render.log" >&2; exit 1; }
echo "$SHARD: rendered, $(du -sh "$DIR/_site" | cut -f1)"

if ! gh repo view "$OWNER/$SHARD" >/dev/null 2>&1; then
  gh repo create "$OWNER/$SHARD" --public \
    --description "Web copies of Damian Betebenner's talks, $YEARS" \
    --homepage "https://dbetebenner.github.io/talks/"
  gh api -X POST "repos/$OWNER/$SHARD/pages" -f build_type=workflow >/dev/null
fi

cd "$DIR"
if [[ ! -d .git ]]; then
  git init -q -b main
  git remote add origin "git@github.com:$OWNER/$SHARD.git"
fi
git add .gitignore .nojekyll README.md _quarto.yml index.html .github/workflows/publish.yml _extensions/deck
for d in 20*/; do git add "${d}index.qmd" "${d}slides"; done
untracked="$(git status --porcelain | grep -v '^[AM] ' || true)"
[[ -z "$untracked" ]] || { echo "unexpected paths in $DIR:"; echo "$untracked"; exit 1; } >&2
if ! git diff --cached --quiet; then
  git commit -qm "Web copies of talks, $YEARS

Generated by dbetebenner.github.io tools/convert/build-decks.mjs; deck theme from the dataimago deck extension."
fi
git push -q -u origin main
cd "$HUB"

if gh release view originals --repo "$OWNER/$SHARD" >/dev/null 2>&1; then
  gh release upload originals --repo "$OWNER/$SHARD" --clobber "$RELEASE"/*
else
  gh release create originals --repo "$OWNER/$SHARD" \
    --title "Original slide files, $YEARS" \
    --notes "The original PDF, PowerPoint, Keynote and LaTeX files behind the web copies of these talks. Each talk page links its own files; the index of talks is at https://dbetebenner.github.io/talks/." \
    "$RELEASE"/*
fi
echo "$SHARD: $(gh release view originals --repo "$OWNER/$SHARD" --json assets --jq '.assets|length') release assets; Pages at https://$OWNER.github.io/$SHARD/"
