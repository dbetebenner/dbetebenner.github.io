#!/usr/bin/env node
// Write the fixed files of each talks-archive shard checkout: Quarto project, redirecting
// index, README, Pages workflow and the vendored deck extension. Deck folders are written
// by tools/convert/build-decks.mjs.
//
//   node tools/shards/scaffold.mjs --root <dir holding the shard checkouts> --extension <path to _extensions/deck>

import fs from 'node:fs';
import path from 'node:path';
import yaml from 'js-yaml';

const args = process.argv.slice(2);
const arg = (name) => (args.includes(name) ? args[args.indexOf(name) + 1] : null);
const ROOT = arg('--root');
const EXTENSION = arg('--extension');
if (!ROOT || !EXTENSION) {
  console.error('usage: scaffold.mjs --root <dir> --extension <path to _extensions/deck>');
  process.exit(2);
}

const { shards, owner, pages_base: pagesBase, release_tag: releaseTag } = yaml.load(fs.readFileSync('catalog/shards.yml', 'utf8'), {
  schema: yaml.CORE_SCHEMA,
});
const QUARTO_VERSION = '1.8.24';

for (const s of shards) {
  const dir = path.join(ROOT, s.repo);
  fs.mkdirSync(dir, { recursive: true });
  const write = (rel, text) => {
    fs.mkdirSync(path.dirname(path.join(dir, rel)), { recursive: true });
    fs.writeFileSync(path.join(dir, rel), text);
  };
  const span = `${s.from}–${s.to}`;
  const hub = `${pagesBase}/talks/`;

  write(
    '_quarto.yml',
    `project:
  type: website
  output-dir: _site
  render:
    - "*/index.qmd"
  resources:
    - index.html
    - .nojekyll

website:
  title: "Talks archive, ${span}"
  site-url: ${pagesBase}/${s.repo}
`,
  );

  write(
    'index.html',
    `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>Talks archive, ${span} · Damian Betebenner</title>
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta http-equiv="refresh" content="0; url=${hub}">
<link rel="canonical" href="${hub}">
</head>
<body>
<p>The talks in this archive are listed at <a href="${hub}">${hub}</a>.</p>
</body>
</html>
`,
  );
  write('.nojekyll', '');
  write('.gitignore', '/.quarto/\n/_site/\n**/*.quarto_ipynb\n.DS_Store\n');

  write(
    'README.md',
    `# Talks archive, ${span}

Web copies of Damian Betebenner's talks from ${span}, published at
<${pagesBase}/${s.repo}/> and listed, with search, on <${hub}>.

Each folder is one talk: \`index.qmd\` is a RevealJS deck whose slides are images of the
original (Keynote, PowerPoint, beamer or PDF), with the slide text kept alongside for search
and screen readers. The deck theme is the \`deck\` Quarto extension in \`_extensions/deck/\`,
shared with the other archive shards.

The PDF and the original file of every talk are assets of the
[\`${releaseTag}\` release](https://github.com/${owner}/${s.repo}/releases/tag/${releaseTag}).

## How this repository is built

Everything here is generated by the tools in
[dbetebenner.github.io](https://github.com/${owner}/dbetebenner.github.io)
(\`tools/convert/build-decks.mjs\` and \`tools/shards/scaffold.mjs\`), so fix a deck there rather
than editing it here. Pushing to \`main\` renders the decks with Quarto ${QUARTO_VERSION} and deploys
GitHub Pages.
`,
  );

  write(
    '.github/workflows/publish.yml',
    `name: Publish decks

on:
  push:
    branches: [main]
  workflow_dispatch:

permissions:
  contents: read
  pages: write
  id-token: write

concurrency:
  group: pages
  cancel-in-progress: true

jobs:
  build:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - uses: quarto-dev/quarto-actions/setup@v2
        with:
          version: ${QUARTO_VERSION}
      - run: quarto render
      - name: Size budget (GitHub Pages refuses sites over 1 GB)
        run: |
          size=$(du -sm _site | cut -f1)
          echo "_site: \${size} MB"
          test "\${size}" -lt 950
      - uses: actions/upload-pages-artifact@v3
        with:
          path: _site

  deploy:
    needs: build
    runs-on: ubuntu-latest
    environment:
      name: github-pages
      url: \${{ steps.deployment.outputs.page_url }}
    steps:
      - id: deployment
        uses: actions/deploy-pages@v4
`,
  );

  fs.rmSync(path.join(dir, '_extensions/deck'), { recursive: true, force: true });
  fs.cpSync(EXTENSION, path.join(dir, '_extensions/deck'), { recursive: true });
  console.log(`scaffolded ${dir}`);
}
